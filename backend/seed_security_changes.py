def seed_security_changes():
    db = SessionLocal()

    try:
        created = 0
        updated = 0

        for item in changes:
            existing = (
                db.query(SecurityChange)
                .filter(
                    SecurityChange.change_id == item["change_id"]
                )
                .first()
            )

            if existing:
                for key, value in item.items():
                    setattr(existing, key, value)

                updated += 1
                continue

            change = SecurityChange(**item)
            db.add(change)
            created += 1

        db.commit()

        print(
            f"Security changes seeded successfully. "
            f"Created: {created}, Updated: {updated}"
        )

    finally:
        db.close()


if __name__ == "__main__":
    seed_security_changes()