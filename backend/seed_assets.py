def seed_assets():
    db = SessionLocal()

    try:
        created = 0
        updated = 0

        for asset_data in assets:
            existing = (
                db.query(SecurityAsset)
                .filter(
                    SecurityAsset.asset_id
                    == asset_data["asset_id"]
                )
                .first()
            )

            if existing:
                for field, value in asset_data.items():
                    setattr(existing, field, value)

                updated += 1
                continue

            asset = SecurityAsset(**asset_data)
            db.add(asset)
            created += 1

        db.commit()

        print(
            f"Security assets seeded successfully. "
            f"Created: {created}, Updated: {updated}"
        )

    finally:
        db.close()


if __name__ == "__main__":
    seed_assets()